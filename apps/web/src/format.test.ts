import { describe, expect, it } from 'vitest';
import { formatPhone, phoneE164, plural } from './format';

describe('телефоны', () => {
  it.each([
    ['+79281824909', '+7 928 182 49 09', '+79281824909'],
    ['89281824909', '+7 928 182 49 09', '+79281824909'],
    ['(928)182-49-09', '+7 928 182 49 09', '+79281824909'],
    ['7 928 182 49 09', '+7 928 182 49 09', '+79281824909'],
  ])('российский номер %s: показ и копирование', (raw, shown, copied) => {
    expect(formatPhone(raw)).toBe(shown);
    expect(phoneE164(raw)).toBe(copied);
  });

  it.each(['+81312345678', '+1 415 555 01 23', '12345', ''])(
    'не российский номер %s — как есть',
    (raw) => {
      // С «+» номер считается российским, только если это +7 и 10 цифр: у +81… восьмёрка —
      // код Японии.
      expect(formatPhone(raw)).toBe(raw);
      expect(phoneE164(raw)).toBe(raw);
    },
  );
});

describe('plural', () => {
  it.each([
    [1, 'заказ'],
    [2, 'заказа'],
    [5, 'заказов'],
    [11, 'заказов'],
    [21, 'заказ'],
    [22, 'заказа'],
    [0, 'заказов'],
  ])('%i → %s', (count, word) => {
    expect(plural(count, ['заказ', 'заказа', 'заказов'])).toBe(word);
  });
});
